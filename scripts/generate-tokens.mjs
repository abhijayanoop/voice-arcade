import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const tokens = JSON.parse(readFileSync('docs/design/tokens.json', 'utf8'))

const resolve = (value) => value.replace(/^\{(.+)\}$/, 'var(--$1)')
const lines = []
const add = (name, value) => lines.push(`  --${name}: ${resolve(value)};`)

for (const t of tokens.color.tokens) add(t.name, t.value)
add('font-display', tokens.type.families.display)
add('font-sans', tokens.type.families.sans)
for (const group of ['spacing', 'motion', 'radius', 'shadow']) {
  for (const t of tokens[group].tokens) add(t.name, t.value)
}

mkdirSync('src/styles', { recursive: true })
writeFileSync(
  'src/styles/tokens.css',
  `/* Generated by scripts/generate-tokens.mjs from docs/design/tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`,
)
console.log(`tokens.css: ${lines.length} variables`)
